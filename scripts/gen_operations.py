"""Prepares generation. Needs PyYAML.

- build/openapi.prep.yaml : the spec without webhook callbacks (server-to-customer, not part of the SDK), so the
                            type generator does not emit event types that have no schema in components.
- src/main/java/com/sitewarm/sdk/Operations.java : operationId -> method/path/idempotency table.

Then run: mvn -B -q -Pgenerate generate-sources
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
spec = yaml.safe_load((ROOT / "openapi" / "openapi.yaml").read_text())

prep = yaml.safe_load(yaml.safe_dump(spec))
prep.pop("webhooks", None)
prep.get("components", {}).pop("callbacks", None)
for item in prep["paths"].values():
    for op in item.values():
        if isinstance(op, dict):
            op.pop("callbacks", None)
(ROOT / "build").mkdir(exist_ok=True)
(ROOT / "build" / "openapi.prep.yaml").write_text(yaml.safe_dump(prep, sort_keys=False))

rows = []
for path, item in spec["paths"].items():
    for method in ("get", "put", "post", "patch", "delete"):
        op = item.get(method)
        if not op:
            continue
        refs = [p.get("$ref", "") for p in [*item.get("parameters", []), *op.get("parameters", [])]]
        idem = next((r for r in refs if r.endswith("/IdempotencyKey") or r.endswith("/IdempotencyKeyRequired")), None)
        kind = "NONE" if not idem else ("REQUIRED" if idem.endswith("Required") else "OPTIONAL")
        rows.append((op["operationId"], method.upper(), path, kind))
rows.sort()

lines = "\n".join(f'        m.put("{i}", new Operation("{m}", "{p}", Operation.Idempotency.{k}));' for i, m, p, k in rows)
out = ROOT / "src" / "main" / "java" / "com" / "sitewarm" / "sdk" / "Operations.java"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "// GENERATED by scripts/gen_operations.py from openapi/openapi.yaml. Do not edit.\n"
    "package com.sitewarm.sdk;\n\n"
    "import java.util.Collections;\n"
    "import java.util.LinkedHashMap;\n"
    "import java.util.Map;\n\n"
    "/** operationId to method, path and idempotency support. */\n"
    "final class Operations {\n"
    "    private Operations() {}\n\n"
    "    static final Map<String, Operation> TABLE = build();\n\n"
    "    private static Map<String, Operation> build() {\n"
    "        Map<String, Operation> m = new LinkedHashMap<>();\n"
    f"{lines}\n"
    "        return Collections.unmodifiableMap(m);\n"
    "    }\n"
    "}\n"
)
(out.parent / "Operation.java").write_text(
    "// GENERATED by scripts/gen_operations.py from openapi/openapi.yaml. Do not edit.\n"
    "package com.sitewarm.sdk;\n\n"
    "record Operation(String method, String path, Idempotency idempotency) {\n"
    "    enum Idempotency { NONE, OPTIONAL, REQUIRED }\n"
    "}\n"
)
print(f"generated {len(rows)} operations")
